#!/usr/bin/env python3
"""Pin every tessdata_fast language file: size and sha256, at one commit.

Copyright 2026 Subtitld contributors
SPDX-License-Identifier: Apache-2.0

The add-on bundles English and downloads any other language the first time a
subtitle asks for it, from tesseract-ocr/tessdata_fast at TESSDATA_COMMIT. It
refuses a file whose size or sha256 differs from the pin this script writes to
tesseract_addon/tessdata_pins.py. Run it again to move to a newer commit:

    python tools/regen_languages.py [--commit SHA] [--cache DIR]

It downloads all 126 files once (about 355 MB); --cache keeps them for reruns.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / 'tesseract_addon' / 'tessdata_pins.py'
DEFAULT_COMMIT = '87416418657359cb625c412a48b6e1d6d41c29bd'  # 2024-08-01, the newest
TREE_URL = 'https://api.github.com/repos/tesseract-ocr/tessdata_fast/git/trees/{commit}'
FILE_URL = 'https://raw.githubusercontent.com/tesseract-ocr/tessdata_fast/{commit}/{name}'


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={'User-Agent': 'subtitld-addon-tesseract'})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--commit', default=DEFAULT_COMMIT)
    parser.add_argument('--cache', type=Path)
    args = parser.parse_args(argv)

    tree = json.loads(fetch(TREE_URL.format(commit=args.commit)))
    names = sorted(entry['path'] for entry in tree['tree'] if entry['path'].endswith('.traineddata'))
    pins: dict[str, tuple[int, str]] = {}
    for count, name in enumerate(names, 1):
        cached = args.cache / name if args.cache else None
        if cached is not None and cached.is_file():
            data = cached.read_bytes()
        else:
            data = fetch(FILE_URL.format(commit=args.commit, name=name))
            if cached is not None:
                cached.parent.mkdir(parents=True, exist_ok=True)
                cached.write_bytes(data)
        pins[name[:-len('.traineddata')]] = (len(data), hashlib.sha256(data).hexdigest())
        print(f'[{count}/{len(names)}] {name} {len(data):,} bytes', file=sys.stderr)

    lines = [
        '"""tessdata_fast files the add-on may download: size and sha256 of each.',
        '',
        'Generated by tools/regen_languages.py; do not edit by hand.',
        '"""',
        '',
        f"TESSDATA_COMMIT = '{args.commit}'",
        "TESSDATA_URL = 'https://raw.githubusercontent.com/tesseract-ocr/tessdata_fast/{commit}/{name}.traineddata'",
        '',
        'PINS = {',
    ]
    lines += [f"    '{name}': ({size}, '{digest}')," for name, (size, digest) in pins.items()]
    lines += ['}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{OUT}: {len(pins)} languages', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
